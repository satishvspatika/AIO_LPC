#!/bin/bash
# Builds the migration image as fw.hex for an old unit's SD bootloader V1.1.
# Production sources (LPC1768/fat_sd, LPC1768/NXP, LPC1768/boot) are compiled read-only; nothing in
# LPC1768/ or LPC845/ is changed by this build. Output: TEST_JIG/migrate/out/fw.hex
set -e
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${HERE}/../.." && pwd)"
LPC="${ROOT}/LPC1768"
OUT="${HERE}/out"
mkdir -p "${OUT}"

if [ -x "${ROOT}/tools/arm-toolchain/bin/arm-none-eabi-gcc" ]; then
    TC="${ROOT}/tools/arm-toolchain/bin/arm-none-eabi-"
elif command -v arm-none-eabi-gcc >/dev/null 2>&1; then
    TC="arm-none-eabi-"
else
    echo "[ERROR] arm-none-eabi-gcc not found"; exit 127
fi

CFLAGS="${MIG_EXTRA_CFLAGS} -mcpu=cortex-m3 -mthumb -Os -g -ffunction-sections -fdata-sections -fcommon -fno-delete-null-pointer-checks -Wall \
  -D__USE_CMSIS=CMSISv1p30_LPC17xx \
  -I${HERE} -I${LPC} -I${LPC}/boot -I${LPC}/fat_sd -I${LPC}/USBHostLite \
  -I${LPC}/NXP/Drivers/include -I${ROOT}/CMSISv1p30_LPC17xx/inc \
  -I${ROOT}/FreeRTOS_Library/include -I${ROOT}/FreeRTOS_Library/portable"

SRCS="${HERE}/startup.c ${HERE}/hal.c ${HERE}/isp845.c ${HERE}/main.c \
  ${LPC}/boot/boot_core.c ${LPC}/boot/fw_journal.c \
  ${LPC}/fat_sd/diskio.c ${LPC}/fat_sd/spi_sd_lpc17xx.c ${LPC}/fat_sd/ff.c ${LPC}/fat_sd/fattime.c \
  ${LPC}/fat_sd/option/ccsbcs.c \
  ${LPC}/NXP/Drivers/source/lpc17xx_pinsel.c ${LPC}/NXP/Drivers/source/lpc17xx_gpio.c \
  ${LPC}/NXP/Drivers/source/lpc17xx_ssp.c ${LPC}/NXP/Drivers/source/lpc17xx_uart.c \
  ${LPC}/NXP/Drivers/source/lpc17xx_clkpwr.c ${LPC}/NXP/Drivers/source/lpc17xx_gpdma.c \
  ${LPC}/NXP/Drivers/source/lpc17xx_libcfg_default.c"

# The LPC845 RAM stub (TEST_JIG/migrate/stub845.s), linked at 0x10000800, as a C array
${TC}gcc -mcpu=cortex-m0plus -mthumb -nostdlib -nostartfiles -Wl,-Ttext=0x10000800 -Wl,-e,stub_start \
  "${HERE}/stub845.s" -o "${OUT}/stub845.elf"
${TC}objcopy -O binary "${OUT}/stub845.elf" "${OUT}/stub845.bin"
python3 - "${OUT}/stub845.bin" "${OUT}/stub845_bin.h" <<'EOF2'
import sys
d = open(sys.argv[1], 'rb').read()
d += b'\0' * (-len(d) % 4)            # ROM "W" takes multiples of 4
body = ', '.join(f'0x{b:02X}' for b in d)
open(sys.argv[2], 'w').write(f"/* Generated by build.sh from stub845.s */\n#define G_STUB845_LEN {len(d)}U\nstatic const unsigned char g_stub845[{len(d)}] = {{ {body} }};\n")
print(f"LPC845 stub: {len(d)} bytes")
EOF2

${TC}gcc ${CFLAGS} -I"${OUT}" --specs=nano.specs --specs=nosys.specs -nostartfiles \
  -Wl,--gc-sections -Wl,-Map="${OUT}/migrate.map" -T "${HERE}/migrate.ld" \
  ${SRCS} -L"${ROOT}/CMSISv1p30_LPC17xx/Debug" -lCMSISv1p30_LPC17xx \
  -o "${OUT}/migrate.elf"
${TC}objcopy -O binary "${OUT}/migrate.elf" "${OUT}/migrate.bin"

# Length and CRC32 into the image info (same rule as scripts/fw_image.py; profile stays 0xFFFFFFFF,
# so no production type is claimed)
python3 - "${OUT}/migrate.bin" <<'EOF'
import struct, sys, zlib
p = sys.argv[1]
d = bytearray(open(p, 'rb').read())
if len(d) % 4:
    d += b'\xff' * (4 - len(d) % 4)
info = struct.unpack_from('<I', d, 8 * 4)[0] - 0x18000
assert struct.unpack_from('<II', d, info) == (0x31474D49, 0x1768), 'no image info'
struct.pack_into('<II', d, info + 8, len(d), 0)
crc = zlib.crc32(bytes(d)) & 0xFFFFFFFF
struct.pack_into('<I', d, info + 12, crc)
open(p, 'wb').write(d)
print(f"Migration image: {len(d)} bytes, CRC32 0x{crc:08X}")
EOF

${TC}objcopy -I binary -O ihex --change-addresses 0x18000 "${OUT}/migrate.bin" "${OUT}/fw.hex.tmp"
grep -vE '^:04000005|^:04000003' "${OUT}/fw.hex.tmp" > "${OUT}/fw.hex"
rm -f "${OUT}/fw.hex.tmp"
python3 "${HERE}/oldboot_check_hex.py" "${OUT}/fw.hex"
${TC}size "${OUT}/migrate.elf"
echo "SD card file: ${OUT}/fw.hex (copy to the card's root as fw.hex)"
