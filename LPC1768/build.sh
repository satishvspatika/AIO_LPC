#!/bin/bash
set -e
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LPC_DIR="${PROJECT_ROOT}/LPC1768"
SCRIPTS_DIR="${PROJECT_ROOT}/scripts"
OUT_DIR="${LPC_DIR}/Debug"
mkdir -p "${OUT_DIR}"

# Auto-detect ARM GCC toolchain and MCUXpresso IDE
MCUX_BIN=$(ls -d /Applications/MCUXpressoIDE*/ide/plugins/com.nxp.mcuxpresso.tools.*/tools/bin 2>/dev/null | tail -n 1 || true)
if [ -z "$MCUX_BIN" ]; then
    MCUX_BIN=$(ls -d /Applications/MCUXpresso\ IDE*/MCUXpresso\ IDE.app/Contents/Eclipse/plugins/com.nxp.mcuxpresso.tools.*/tools/bin 2>/dev/null | tail -n 1 || true)
fi

if [ -n "$MCUX_BIN" ] && [ -x "${MCUX_BIN}/arm-none-eabi-gcc" ]; then
    TC_DIR="${MCUX_BIN}"
    CC="${TC_DIR}/arm-none-eabi-gcc"
    AS="${TC_DIR}/arm-none-eabi-as"
    LD="${TC_DIR}/arm-none-eabi-ld"
    OBJCOPY="${TC_DIR}/arm-none-eabi-objcopy"
    SIZE="${TC_DIR}/arm-none-eabi-size"
    MCUX_TOOLS=$(cd "${MCUX_BIN}/.." && pwd)
elif [ -x "${PROJECT_ROOT}/tools/arm-toolchain/bin/arm-none-eabi-gcc" ]; then
    TC_DIR="${PROJECT_ROOT}/tools/arm-toolchain/bin"
    CC="${TC_DIR}/arm-none-eabi-gcc"
    AS="${TC_DIR}/arm-none-eabi-as"
    LD="${TC_DIR}/arm-none-eabi-ld"
    OBJCOPY="${TC_DIR}/arm-none-eabi-objcopy"
    SIZE="${TC_DIR}/arm-none-eabi-size"
elif command -v arm-none-eabi-gcc >/dev/null 2>&1; then
    CC="arm-none-eabi-gcc"
    AS="arm-none-eabi-as"
    LD="arm-none-eabi-ld"
    OBJCOPY="arm-none-eabi-objcopy"
    SIZE="arm-none-eabi-size"
else
    echo "[ERROR] arm-none-eabi-gcc toolchain not found!"
    exit 127
fi

echo "=== 1. Compiling Clean AIO LPC1768 Sources ==="
# PRODUCTION_BUILD in user_config.h: 1 leaves out -DDEBUG (the NXP drivers' parameter checks)
PRODUCTION_BUILD="$(awk '$1 == "#define" && $2 == "PRODUCTION_BUILD" {print $3}' "${LPC_DIR}/user_config.h")"
TESTING_DEBUG_LOG="$(awk '$1 == "#define" && $2 == "TESTING_DEBUG_LOG" {print $3}' "${LPC_DIR}/user_config.h")"
if [ "${PRODUCTION_BUILD}" = "1" ] && [ "${TESTING_DEBUG_LOG}" = "1" ]; then
    DEBUG_FLAG=""
    echo "TESTING build (PRODUCTION_BUILD 1, TESTING_DEBUG_LOG 1): no -DDEBUG, KEY TEST hidden, debug log ON by default"
    echo "    For the production release set TESTING_DEBUG_LOG 0 in user_config.h"
elif [ "${PRODUCTION_BUILD}" = "1" ]; then
    DEBUG_FLAG=""
    echo "Production build (PRODUCTION_BUILD 1): no -DDEBUG, KEY TEST hidden, debug log only with DEBUGLOG.ON"
elif [ "${PRODUCTION_BUILD}" = "0" ]; then
    DEBUG_FLAG="-DDEBUG"
    echo "Bench build (PRODUCTION_BUILD 0): -DDEBUG, KEY TEST shown, debug log on"
else
    echo "[ERROR] PRODUCTION_BUILD line not found in user_config.h"; exit 1
fi
CFLAGS="-c -mcpu=cortex-m3 -mthumb -Os -g -fcommon -ffunction-sections -fdata-sections \
  ${DEBUG_FLAG} -D__USE_CMSIS=CMSISv1p30_LPC17xx \
  -I${LPC_DIR} \
  -I${PROJECT_ROOT}/CMSISv1p30_LPC17xx/inc \
  -I${PROJECT_ROOT}/FreeRTOS_Library/include \
  -I${PROJECT_ROOT}/FreeRTOS_Library/portable \
  -I${PROJECT_ROOT}/FreeRTOS_Library/demo_code \
  -I${LPC_DIR}/NXP/Drivers/include \
  -I${LPC_DIR}/fat_sd \
  -I${LPC_DIR}/USBHostLite"

# LPC845 pieces for the CTRL ROM loader route (ctrl_isp.c): RAM stub, rescue sector 0 and the
# CTRL bootloader, as C arrays in ${OUT_DIR}/ctrl_isp_img.h
${CC} -mcpu=cortex-m0plus -mthumb -nostdlib -nostartfiles -Wl,-Ttext=0x10000800 -Wl,-e,stub_start \
  "${LPC_DIR}/ctrl_isp/stub845.s" -o "${OUT_DIR}/stub845.elf"
${OBJCOPY} -O binary "${OUT_DIR}/stub845.elf" "${OUT_DIR}/stub845.bin"
${CC} -mcpu=cortex-m0plus -mthumb -nostdlib -nostartfiles -Wl,-Ttext=0x0 -Wl,-e,rescue_vectors \
  "${LPC_DIR}/ctrl_isp/rescue845.s" -o "${OUT_DIR}/rescue845.elf"
${OBJCOPY} -O binary "${OUT_DIR}/rescue845.elf" "${OUT_DIR}/rescue845.bin"
python3 "${SCRIPTS_DIR}/lpc_checksum.py" "${OUT_DIR}/rescue845.bin" >/dev/null
python3 - "${OUT_DIR}/stub845.bin" "${OUT_DIR}/rescue845.bin" "${PROJECT_ROOT}/LPC845/LPC845_BOOT.bin" "${OUT_DIR}/ctrl_isp_img.h" <<'EOF_ISP'
import struct, sys
stub, rescue, boot = (open(p, 'rb').read() for p in sys.argv[1:4])
stub += b'\0' * (-len(stub) % 4)            # ROM "W" takes multiples of 4
assert sum(struct.unpack_from('<8I', rescue, 0)) & 0xFFFFFFFF == 0, 'rescue vector checksum'
assert sum(struct.unpack_from('<8I', boot, 0)) & 0xFFFFFFFF == 0, 'CTRL bootloader vector checksum'
assert len(boot) <= 0x2400, 'CTRL bootloader runs into the firmware slot'
if len(boot) > 0x2FF:
    assert struct.unpack_from('<I', boot, 0x2FC)[0] not in (0x12345678, 0x87654321, 0x43218765, 0x4E697370), 'CRP value at 0x2FC'
def arr(name, d):
    return f"#define {name.upper()}_LEN {len(d)}U\nstatic const unsigned char {name}[{len(d)}] = {{ " + ', '.join(f'0x{b:02X}' for b in d) + " };\n"
with open(sys.argv[4], 'w') as f:
    f.write("/* Generated by build.sh: LPC845 RAM stub, rescue sector 0 and CTRL bootloader (LPC845_BOOT.bin) */\n")
    f.write(arr('g_stub845', stub) + arr('g_rescue845', rescue) + arr('g_ctrl_boot', boot))
print(f"CTRL ROM loader route: stub {len(stub)} B, rescue {len(rescue)} B, CTRL bootloader {len(boot)} B")
EOF_ISP

# Compile modular sources
${CC} ${CFLAGS} -I"${OUT_DIR}" "${LPC_DIR}/ctrl_isp.c" -o "${OUT_DIR}/ctrl_isp.o"
${CC} ${CFLAGS} "${LPC_DIR}/ctrl_isp_core.c" -o "${OUT_DIR}/ctrl_isp_core.o"
${CC} ${CFLAGS} "${LPC_DIR}/main.c" -o "${OUT_DIR}/main.o"
${CC} ${CFLAGS} "${LPC_DIR}/hal_power.c" -o "${OUT_DIR}/hal_power.o"
${CC} ${CFLAGS} "${LPC_DIR}/intermcu_protocol.c" -o "${OUT_DIR}/intermcu_protocol.o"
${CC} ${CFLAGS} "${LPC_DIR}/telemetry_formatter.c" -o "${OUT_DIR}/telemetry_formatter.o"
${CC} ${CFLAGS} "${LPC_DIR}/sim7600_driver.c" -o "${OUT_DIR}/sim7600_driver.o"
${CC} ${CFLAGS} "${LPC_DIR}/ui_display.c" -o "${OUT_DIR}/ui_display.o"
${CC} ${CFLAGS} "${LPC_DIR}/storage_log.c" -o "${OUT_DIR}/storage_log.o"
${CC} ${CFLAGS} "${LPC_DIR}/flash_nvram.c" -o "${OUT_DIR}/flash_nvram.o"
${CC} ${CFLAGS} "${LPC_DIR}/flash_log.c" -o "${OUT_DIR}/flash_log.o"
${CC} ${CFLAGS} "${LPC_DIR}/fw_app.c" -o "${OUT_DIR}/fw_app.o"
${CC} ${CFLAGS} "${LPC_DIR}/fw_update.c" -o "${OUT_DIR}/fw_update.o"
${CC} ${CFLAGS} "${LPC_DIR}/fw_ctrl.c" -o "${OUT_DIR}/fw_ctrl.o"
${CC} ${CFLAGS} "${LPC_DIR}/errlog.c" -o "${OUT_DIR}/errlog.o"
${CC} ${CFLAGS} "${LPC_DIR}/net_policy.c" -o "${OUT_DIR}/net_policy.o"
${CC} ${CFLAGS} "${LPC_DIR}/sms_cmd.c" -o "${OUT_DIR}/sms_cmd.o"
mkdir -p "${OUT_DIR}/boot"
${CC} ${CFLAGS} "${LPC_DIR}/boot/fw_journal.c" -o "${OUT_DIR}/boot/fw_journal.o"
${CC} ${CFLAGS} "${LPC_DIR}/cr_startup_lpc17.c" -o "${OUT_DIR}/cr_startup_lpc17.o"

# The kernel is built here so FreeRTOSConfig.h takes effect: the prebuilt library ignored its stack
# overflow setting. -O1 is what that library used.
RTOS_DIR="${PROJECT_ROOT}/FreeRTOS_Library"
RTOS_FLAGS="-c -mcpu=cortex-m3 -mthumb -O1 -g -fcommon -I${RTOS_DIR}/include -I${RTOS_DIR}/portable -I${RTOS_DIR}/demo_code -I${PROJECT_ROOT}/CMSISv1p30_LPC17xx/inc"
mkdir -p "${OUT_DIR}/rtos"
for src in tasks list queue portable/port portable/heap_2; do
    ${CC} ${RTOS_FLAGS} "${RTOS_DIR}/${src}.c" -o "${OUT_DIR}/rtos/$(basename ${src}).o"
done

# Compile FatFs drivers
mkdir -p "${OUT_DIR}/fat_sd/option"
${CC} ${CFLAGS} "${LPC_DIR}/fat_sd/diskio.c" -o "${OUT_DIR}/fat_sd/diskio.o"
${CC} ${CFLAGS} "${LPC_DIR}/fat_sd/spi_sd_lpc17xx.c" -o "${OUT_DIR}/fat_sd/spi_sd_lpc17xx.o"
${CC} ${CFLAGS} "${LPC_DIR}/fat_sd/ff.c" -o "${OUT_DIR}/fat_sd/ff.o"
${CC} ${CFLAGS} "${LPC_DIR}/fat_sd/fattime.c" -o "${OUT_DIR}/fat_sd/fattime.o"
${CC} ${CFLAGS} "${LPC_DIR}/fat_sd/option/ccsbcs.c" -o "${OUT_DIR}/fat_sd/option/ccsbcs.o"

# Compile NXP Peripheral Drivers
mkdir -p "${OUT_DIR}/NXP/Drivers/source"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_adc.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_adc.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_clkpwr.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_clkpwr.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_gpdma.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_gpdma.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_gpio.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_gpio.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_i2c.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_i2c.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_nvic.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_nvic.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_pinsel.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_pinsel.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_ssp.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_ssp.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_uart.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_uart.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_wdt.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_wdt.o"
${CC} ${CFLAGS} "${LPC_DIR}/NXP/Drivers/source/lpc17xx_libcfg_default.c" -o "${OUT_DIR}/NXP/Drivers/source/lpc17xx_libcfg_default.o"

# Compile USBHostLite
mkdir -p "${OUT_DIR}/USBHostLite"
${CC} ${CFLAGS} "${LPC_DIR}/USBHostLite/rtc_cal.c" -o "${OUT_DIR}/USBHostLite/rtc_cal.o"
${CC} ${CFLAGS} "${LPC_DIR}/USBHostLite/usbhost_lpc17xx.c" -o "${OUT_DIR}/USBHostLite/usbhost_lpc17xx.o"
${CC} ${CFLAGS} "${LPC_DIR}/USBHostLite/usbhost_ms.c" -o "${OUT_DIR}/USBHostLite/usbhost_ms.o"

echo "=== 2. Linking LPC1768_AIO.axf ==="
${CC} \
  -mcpu=cortex-m3 -mthumb \
  --specs=nano.specs --specs=nosys.specs \
  -L"${PROJECT_ROOT}/CMSISv1p30_LPC17xx/Debug" \
  -L"${PROJECT_ROOT}/FreeRTOS_Library/Debug" \
  -L"${OUT_DIR}" \
  -Xlinker --gc-sections \
  -Xlinker -Map="${OUT_DIR}/LPC1768_AIO.map" \
  -T "${LPC_DIR}/Debug/example01_gnu.ld" \
  -o "${OUT_DIR}/LPC1768_AIO.axf" \
  "${OUT_DIR}/cr_startup_lpc17.o" \
  "${OUT_DIR}/rtos/tasks.o" \
  "${OUT_DIR}/rtos/list.o" \
  "${OUT_DIR}/rtos/queue.o" \
  "${OUT_DIR}/rtos/port.o" \
  "${OUT_DIR}/rtos/heap_2.o" \
  "${OUT_DIR}/main.o" \
  "${OUT_DIR}/hal_power.o" \
  "${OUT_DIR}/intermcu_protocol.o" \
  "${OUT_DIR}/telemetry_formatter.o" \
  "${OUT_DIR}/sim7600_driver.o" \
  "${OUT_DIR}/ui_display.o" \
  "${OUT_DIR}/storage_log.o" \
  "${OUT_DIR}/flash_log.o" \
  "${OUT_DIR}/fw_app.o" \
  "${OUT_DIR}/fw_update.o" \
  "${OUT_DIR}/fw_ctrl.o" \
  "${OUT_DIR}/errlog.o" \
  "${OUT_DIR}/net_policy.o" \
  "${OUT_DIR}/sms_cmd.o" \
  "${OUT_DIR}/ctrl_isp.o" \
  "${OUT_DIR}/ctrl_isp_core.o" \
  "${OUT_DIR}/boot/fw_journal.o" \
  "${OUT_DIR}/flash_nvram.o" \
  "${OUT_DIR}/fat_sd/diskio.o" \
  "${OUT_DIR}/fat_sd/spi_sd_lpc17xx.o" \
  "${OUT_DIR}/fat_sd/ff.o" \
  "${OUT_DIR}/fat_sd/fattime.o" \
  "${OUT_DIR}/fat_sd/option/ccsbcs.o" \
  "${OUT_DIR}/USBHostLite/rtc_cal.o" \
  "${OUT_DIR}/USBHostLite/usbhost_lpc17xx.o" \
  "${OUT_DIR}/USBHostLite/usbhost_ms.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_adc.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_clkpwr.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_gpdma.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_gpio.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_i2c.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_nvic.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_pinsel.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_ssp.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_uart.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_wdt.o" \
  "${OUT_DIR}/NXP/Drivers/source/lpc17xx_libcfg_default.o" \
  -lCMSISv1p30_LPC17xx -lFreeRTOS_Library -lm

echo "=== 3. Assembling Sector 0 Boot Stub ==="
${AS} -mcpu=cortex-m3 -mthumb "${SCRIPTS_DIR}/boot_stub.s" -o "${OUT_DIR}/boot_stub.o"
${LD} -T "${SCRIPTS_DIR}/boot_stub.ld" "${OUT_DIR}/boot_stub.o" -o "${OUT_DIR}/boot_stub.elf"
${OBJCOPY} -O binary "${OUT_DIR}/boot_stub.elf" "${OUT_DIR}/boot_stub.bin"
python3 "${SCRIPTS_DIR}/lpc_checksum.py" "${OUT_DIR}/boot_stub.bin"
${OBJCOPY} -I binary -O ihex --change-addresses 0x00000000 "${OUT_DIR}/boot_stub.bin" "${OUT_DIR}/boot_stub.hex"

echo "=== 4. Building Bootloader (0x2000) ==="
BOOT_FLAGS="-mcpu=cortex-m3 -mthumb -Os -g -ffreestanding -fno-builtin -ffunction-sections -fdata-sections -Wall \
  -D__USE_CMSIS=CMSISv1p30_LPC17xx -I${LPC_DIR}/boot -I${PROJECT_ROOT}/CMSISv1p30_LPC17xx/inc"
${CC} ${BOOT_FLAGS} -nostartfiles -nostdlib -Wl,--gc-sections -T "${LPC_DIR}/boot/boot.ld" \
  "${LPC_DIR}/boot/boot_main.c" "${LPC_DIR}/boot/boot_core.c" "${LPC_DIR}/boot/fw_journal.c" \
  -lgcc -o "${OUT_DIR}/bootloader.elf"
${OBJCOPY} -O ihex "${OUT_DIR}/bootloader.elf" "${OUT_DIR}/bootloader.hex"
${SIZE} "${OUT_DIR}/bootloader.elf"

echo "=== 5. Merging Boot Stub + Bootloader + Blank Journal + Application (0x18000) ==="
${OBJCOPY} -O binary "${OUT_DIR}/LPC1768_AIO.axf" "${OUT_DIR}/LPC1768_AIO.bin"
python3 "${SCRIPTS_DIR}/fw_image.py" "${OUT_DIR}/LPC1768_AIO.bin"
${OBJCOPY} -I binary -O ihex --change-addresses 0x00018000 "${OUT_DIR}/LPC1768_AIO.bin" "${OUT_DIR}/LPC1768_AIO_APP.hex"
# Data records only: start addresses (record types 03 and 05) and end records come off each part
HEX_STRIP='^:00000001FF|^:04000005|^:04000003'
grep -vE "${HEX_STRIP}" "${OUT_DIR}/boot_stub.hex" > "${OUT_DIR}/LPC1768_AIO_FULL.hex"
grep -vE "${HEX_STRIP}" "${OUT_DIR}/bootloader.hex" >> "${OUT_DIR}/LPC1768_AIO_FULL.hex"
# Flashing with the probe starts the update journal afresh
python3 -c "import sys; sys.stdout.buffer.write(b'\xff' * 0x4000)" > "${OUT_DIR}/journal_blank.bin"
${OBJCOPY} -I binary -O ihex --change-addresses 0x0000C000 "${OUT_DIR}/journal_blank.bin" "${OUT_DIR}/journal_blank.hex"
grep -vE "${HEX_STRIP}" "${OUT_DIR}/journal_blank.hex" >> "${OUT_DIR}/LPC1768_AIO_FULL.hex"
grep -vE "${HEX_STRIP}" "${OUT_DIR}/LPC1768_AIO_APP.hex" >> "${OUT_DIR}/LPC1768_AIO_FULL.hex"
echo ":00000001FF" >> "${OUT_DIR}/LPC1768_AIO_FULL.hex"
python3 "${SCRIPTS_DIR}/fw_check_hex.py" "${OUT_DIR}/LPC1768_AIO_FULL.hex"
# The file for MENU > FIRMWARE UPDATE: copy this one to the SD card. One per station type.
SD_FILE="$(cat "${OUT_DIR}/LPC1768_AIO.bin.sdname")"
rm -f "${OUT_DIR}/fw.hex"
cp "${OUT_DIR}/LPC1768_AIO_APP.hex" "${OUT_DIR}/${SD_FILE}"

${SIZE} "${OUT_DIR}/LPC1768_AIO.axf"
echo "=== LPC1768 Build Completed Successfully! ==="
echo "Full Flashing HEX: ${OUT_DIR}/LPC1768_AIO_FULL.hex"
echo "SD card update file: ${OUT_DIR}/${SD_FILE}"
